"""Tokens as CSS custom properties, a Typst module and JSON."""

import json

from tokens import Section, Tokens


def css(tokens: Tokens) -> str:
    lines = [":root {"]
    for ramp, steps in tokens.palette.ramps.items():
        lines += [f"  --{ramp}-{step}: {color};" for step, color in steps.items()]
    for role, face in tokens.type.faces.items():
        lines.append(f"  --font-{role}: {face.stack()};")
    for step in tokens.type.scale.steps:
        lines.append(f"  --size-{step}: {tokens.type.scale.size(step)}px;")
    lines.append("}")
    for theme in tokens.themes:
        lines.append(f'[data-theme="{theme.name}"] {{')
        for section in Section:
            for role, ref in theme.roles[section].items():
                lines.append(f"  --{section.value}-{role}: var(--{ref.ramp}-{ref.step});")
        lines.append("}")
    return "\n".join(lines) + "\n"


def typst(tokens: Tokens) -> str:
    def dictionary(entries: dict[str, str]) -> str:
        return "(" + ", ".join(f'"{key}": {value}' for key, value in entries.items()) + ")"

    lines = ["// Generated by design/tools/build.py from design/tokens and design/themes."]
    ramps = {
        ramp: dictionary({step: f'rgb("{color}")' for step, color in steps.items()})
        for ramp, steps in tokens.palette.ramps.items()
    }
    lines.append(f"#let palette = {dictionary(ramps)}")
    for theme in tokens.themes:
        sections = {
            section.value: dictionary(
                {role: f'rgb("{color}")' for role, color in theme.resolve(tokens.palette, section).items()}
            )
            for section in Section
        }
        lines.append(f"#let {theme.name} = {dictionary(sections)}")
    return "\n".join(lines) + "\n"


def data(tokens: Tokens) -> str:
    return json.dumps(
        {
            "palette": tokens.palette.ramps,
            "themes": {
                theme.name: {
                    section.value: theme.resolve(tokens.palette, section) for section in Section
                }
                for theme in tokens.themes
            },
            "type": {
                role: {"family": face.family, "fallback": face.fallback, "weights": face.weights}
                for role, face in tokens.type.faces.items()
            },
        },
        indent=2,
    ) + "\n"
