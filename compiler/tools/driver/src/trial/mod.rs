//! Trying a program through everything (spec 11): checked, lowered and verified at each stage,
//! then built and run by every backend that generates code for the target, which must agree.
//! A program made to be accepted that is not, or that is not lowered, or that the backends run
//! differently, is a finding. Nothing here knows how programs are made.

mod attempt;
mod finding;

use std::time::Duration;

use vun_diag::{DiagCtxt, Severity};
use vun_intern::Symbol;
use vun_span::FileId;

pub use attempt::Agreed;
pub use finding::{Cause, Death, Finding, Lacking, Parting, Report, Stage};

use crate::Session;
use crate::compare::Ran;
use crate::crash::Catching;

/// How far a program is taken.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, vun_variants::Variants)]
pub enum Reach {
    /// Checked, and MIR and LIR built and verified.
    Front,
    /// And its code generated by each backend, in this process.
    Code,
    /// And linked, run and compared.
    #[default]
    Run,
}

impl Reach {
    /// The name the command line gives it.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Front => "front",
            Self::Code => "code",
            Self::Run => "run",
        }
    }

    /// The reach a name gives.
    #[must_use]
    pub fn named(name: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|r| r.name() == name)
    }
}

/// How a program is tried.
#[derive(Clone, Debug)]
pub struct Trial {
    pub reach: Reach,
    /// How long a program may run.
    pub limit: Duration,
    /// The backends to build through, in order; those of the target that generate code when empty.
    pub backends: Vec<Symbol>,
}

impl Default for Trial {
    fn default() -> Self {
        Self { reach: Reach::default(), limit: Duration::from_secs(10), backends: Vec::new() }
    }
}

impl Session {
    /// The program rooted at `file`, tried as `trial` says.
    ///
    /// # Errors
    /// Returns what was wrong with it, the first stage that finds anything.
    pub fn trial(&mut self, catching: &Catching, file: FileId, trial: &Trial) -> Result<Agreed, Finding> {
        Trying { session: self, catching, trial }.through(file)
    }
}

/// A program being tried: the session that compiles it, and what catches the compiler's panics.
struct Trying<'s> {
    session: &'s mut Session,
    catching: &'s Catching,
    trial: &'s Trial,
}

/// One stage of the front end, run over a file.
type Check<'a> = fn(&mut Trying<'a>, FileId) -> Result<(), Finding>;

impl Trying<'_> {
    fn through(mut self, file: FileId) -> Result<Agreed, Finding> {
        self.front(file)?;
        if self.trial.reach == Reach::Front {
            return Ok(Agreed::default());
        }
        let target = self.session.target.clone().expect("naming a file chooses the target");
        let target = target.map_err(|_| Finding::Rejected(self.reports()))?;
        let backends: Vec<&'static str> = if self.trial.backends.is_empty() {
            self.session.registry.fitting(&target).map(|b| b.info().id.0).collect()
        } else {
            self.trial.backends.iter().map(|b| b.as_str()).collect()
        };
        let (mut ran, mut lacking) = (Vec::new(), Vec::new());
        for backend in backends {
            let result = match self.trial.reach {
                Reach::Run => self.attempt(file, backend).map(|r| ran.push(r)),
                Reach::Code | Reach::Front => self.generate(file, backend),
            };
            match result {
                Err(finding) if finding.is_lack() => lacking.push(backend),
                other => other?,
            }
        }
        Self::agree(&ran, lacking)
    }

    /// The checks, MIR and LIR of `file`, each verified.
    fn front(&mut self, file: FileId) -> Result<(), Finding> {
        self.session.diag = DiagCtxt::default();
        let catching = self.catching;
        let stages: [(Stage, Check<'_>); 3] =
            [(Stage::Check, Self::checks), (Stage::Mir, Self::mir), (Stage::Lir, Self::lir)];
        for (stage, run) in stages {
            catching
                .run(|| run(self, file))
                .map_err(|site| Finding::Crashed { stage, site })
                .and_then(|found| found)?;
        }
        Ok(())
    }

    fn checks(&mut self, file: FileId) -> Result<(), Finding> {
        self.session.check(file);
        let reports = self.reports();
        if reports.is_empty() { Ok(()) } else { Err(Finding::Rejected(reports)) }
    }

    fn mir(&mut self, file: FileId) -> Result<(), Finding> {
        for (function, body) in self.session.bodies(file) {
            // A generic function has the bodies of its instantiations, which lowering builds.
            if self.session.is_generic(file, &function) {
                continue;
            }
            match body {
                Ok(body) => body.verify(self.session.origins).map_err(|reason| Finding::Malformed {
                    stage: Stage::Mir,
                    reason: format!("{function:?}: {reason:?}"),
                })?,
                Err(unbuilt) => {
                    let lacking = Lacking::Mir(unbuilt.by, unbuilt.why);
                    return Err(Finding::Unlowered { stage: Stage::Mir, lacking });
                }
            }
        }
        Ok(())
    }

    fn lir(&mut self, file: FileId) -> Result<(), Finding> {
        match &*self.session.lir(file) {
            Ok(unit) => unit
                .verify(self.session.origins)
                .map_err(|reason| Finding::Malformed { stage: Stage::Lir, reason: format!("{reason:?}") }),
            Err(unlowered) => {
                Err(Finding::Unlowered { stage: Stage::Lir, lacking: Lacking::Lir(unlowered.why.clone()) })
            }
        }
    }

    /// The errors reported so far.
    fn reports(&self) -> Vec<Report> {
        let errors = self
            .session
            .diag
            .sorted(self.session.origins)
            .into_iter()
            .filter(|d| d.severity == Severity::Error);
        errors.map(|d| Report { id: d.id, message: d.message.to_string() }).collect()
    }

    /// What every run wrote, if they agree; where they part, if not.
    fn agree(ran: &[Ran], lacking: Vec<&'static str>) -> Result<Agreed, Finding> {
        if ran.is_empty() {
            return Ok(Agreed { backends: Vec::new(), lacking, stdout: Vec::new() });
        }
        let reference = &ran[Ran::consensus(ran).0];
        let partings: Vec<Parting> = ran
            .iter()
            .filter_map(|r| r.differs(reference).map(|difference| Parting { backend: r.backend, difference }))
            .collect();
        if partings.is_empty() {
            Ok(Agreed {
                backends: ran.iter().map(|r| r.backend).collect(),
                lacking,
                stdout: reference.output.stdout.clone(),
            })
        } else {
            Err(Finding::Parted { reference: reference.backend, partings })
        }
    }
}
