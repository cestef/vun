//! The members of `struct` and `enum` types (spec 02, section 2): fields and declarations, which
//! make a struct's namespace with what its spreads bring, and variants. A struct built in a
//! compile-time call has its members evaluated inside that call, so `Pair(u8)` has fields of type
//! `u8`.

mod query;
mod table;

pub use query::{MemberType, MemberValue};
pub use table::Members;

use vun_codec::{Decode, Encode};
use vun_intern::Symbol;
use vun_sema_ty::Ty;
use vun_sema_ty::call::Staging;
use vun_sema_ty::item::{DeclRef, ExprRef, Site};
use vun_sema_ty::trap::Unevaluated;

use crate::visible::Visible;

#[derive(Debug, Default, PartialEq, Eq, Hash, Encode, Decode)]
pub struct MemberTable {
    /// Fields in declaration order.
    pub fields: Vec<Field>,
    pub decls: Vec<MemberDecl>,
    /// An enum's variants, in declaration order.
    pub variants: Vec<VariantDef>,
    /// The members spreads bring, each where it is declared (spec 01, section 8).
    pub spread: Vec<(Symbol, Site)>,
    /// Whether every member is known, none generated by `$for` or `$if` or computed, and every
    /// spread read: only then is a name missing from the table no member at all.
    pub complete: bool,
    /// The pointer field `#[kind.owns]` marks, which `.*` reads through.
    pub deref: Option<Symbol>,
}

impl MemberTable {
    /// The field `.*` reads through and the type it points to, for a struct owning its target.
    #[must_use]
    pub fn deref(&self) -> Option<(Symbol, Ty)> {
        let name = self.deref?;
        let field = self.fields.iter().find(|f| f.name == name)?;
        Some((name, field.ty.as_ref().ok()?.pointee()?))
    }
}

#[derive(Debug, PartialEq, Eq, Hash, Encode, Decode)]
pub struct Field {
    pub name: Symbol,
    pub ty: Result<Ty, Unevaluated>,
    pub visible: Visible,
    /// The value a literal that omits the field gives it, evaluated where the struct was built.
    pub default: Option<ExprRef>,
    /// The offset `#[layout.offset(n)]` places it at, in bytes.
    pub offset: Option<u64>,
}

#[derive(Debug, PartialEq, Eq, Hash, Encode, Decode)]
pub struct MemberDecl {
    pub name: Symbol,
    pub decl: DeclRef,
    pub visible: Visible,
    /// The `$for` bindings it was generated under, which its value sees.
    pub staged: Vec<Staging>,
}

#[derive(Debug, PartialEq, Eq, Hash, Encode, Decode)]
pub struct VariantDef {
    pub name: Symbol,
    pub payload: Vec<Result<Ty, Unevaluated>>,
}

/// What a name is among a type's members.
#[derive(Debug, PartialEq, Eq)]
pub enum Found<'m> {
    Field(&'m Field),
    Decl(&'m MemberDecl),
    Variant(&'m VariantDef),
    /// A member a spread brings, where it is declared.
    Spread(&'m Site),
    Absent,
    /// Not among the members written literally, but perhaps generated.
    Unknown,
}

impl MemberTable {
    #[must_use]
    pub fn find(&self, name: Symbol) -> Found<'_> {
        if let Some(field) = self.fields.iter().find(|f| f.name == name) {
            return Found::Field(field);
        }
        if let Some(decl) = self.decls.iter().find(|d| d.name == name) {
            return Found::Decl(decl);
        }
        if let Some(variant) = self.variants.iter().find(|v| v.name == name) {
            return Found::Variant(variant);
        }
        if let Some((_, site)) = self.spread.iter().find(|(n, _)| *n == name) {
            return Found::Spread(site);
        }
        if self.complete { Found::Absent } else { Found::Unknown }
    }
}
