//! Diagnostics with their children and traces.

use std::fmt;

use vun_origin::OriginId;

use crate::{DiagId, DiagSource, Fix, Label, Msg, Severity};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ChildKind {
    /// A fact.
    Note,
    /// A suggestion.
    Help,
    /// What caused the diagnostic, then what caused that, outermost first.
    Cause,
}

impl ChildKind {
    /// How renderers title it.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Note => "note",
            Self::Help => "help",
            Self::Cause => "caused by",
        }
    }
}

impl fmt::Display for ChildKind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.name())
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Child {
    pub kind: ChildKind,
    pub msg: Msg,
    pub labels: Vec<Label>,
    pub fixes: Vec<Fix>,
}

/// Context such as "while evaluating", "instantiated from", "generated by".
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct TraceFrame {
    pub msg: Msg,
    pub origin: OriginId,
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Diagnostic {
    pub id: DiagId,
    pub severity: Severity,
    pub source: DiagSource,
    pub message: Msg,
    /// `None` only when there is no source location, such as a missing input file.
    pub primary: Option<Label>,
    pub labels: Vec<Label>,
    pub children: Vec<Child>,
    pub fixes: Vec<Fix>,
    /// Innermost first.
    pub trace: Vec<TraceFrame>,
}

impl Diagnostic {
    #[must_use]
    pub fn new(id: DiagId, severity: Severity, message: impl Into<Msg>) -> Self {
        Self {
            id,
            severity,
            source: DiagSource::Compiler,
            message: message.into(),
            primary: None,
            labels: Vec::new(),
            children: Vec::new(),
            fixes: Vec::new(),
            trace: Vec::new(),
        }
    }

    #[must_use]
    pub fn error(id: DiagId, message: impl Into<Msg>) -> Self {
        Self::new(id, Severity::Error, message)
    }

    #[must_use]
    pub fn at(mut self, origin: OriginId, msg: Option<Msg>) -> Self {
        self.primary = Some(Label { origin, msg });
        self
    }

    /// Adds a secondary label.
    #[must_use]
    pub fn label(mut self, origin: OriginId, msg: Option<Msg>) -> Self {
        self.labels.push(Label { origin, msg });
        self
    }

    #[must_use]
    pub fn fix(mut self, fix: Fix) -> Self {
        self.fixes.push(fix);
        self
    }

    #[must_use]
    pub fn child(mut self, kind: ChildKind, msg: impl Into<Msg>) -> Self {
        self.children.push(Child { kind, msg: msg.into(), labels: Vec::new(), fixes: Vec::new() });
        self
    }

    /// One [`ChildKind::Cause`] for `error` and each of its sources in turn.
    #[must_use]
    pub fn caused_by(self, error: &(dyn std::error::Error + 'static)) -> Self {
        std::iter::successors(Some(error), |e| e.source())
            .fold(self, |d, e| d.child(ChildKind::Cause, Msg::new().text(e.to_string())))
    }
}
