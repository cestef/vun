//! The diagnostic model: labels, fixes, severities, sinks (spec 10, section 2).
//!
//! Diagnostics are data; rendering is a separate concern behind [`DiagSink`].

pub mod errors;

use std::borrow::Cow;
use std::fmt;

use overt_origin::{OriginId, OriginTable};
use overt_span::{SourceMap, Span};

/// A binding path to a `lang.diag.Diag` value, such as `lang.errors.int.does_not_fit`.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct DiagId(pub Cow<'static, str>);

impl DiagId {
    /// Prefix under which compiler errors live; they are displayed relative to it.
    pub const COMPILER: &'static str = "lang.errors.";

    /// An id known at compile time.
    #[must_use]
    pub const fn new(path: &'static str) -> Self {
        Self(Cow::Borrowed(path))
    }
}

impl fmt::Display for DiagId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.0.strip_prefix(Self::COMPILER).unwrap_or(&self.0))
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Severity {
    Hint,
    Info,
    Warning,
    Error,
}

impl fmt::Display for Severity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Hint => "hint",
            Self::Info => "info",
            Self::Warning => "warning",
            Self::Error => "error",
        })
    }
}

/// What produced a diagnostic.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DiagSource {
    Compiler,
    Lint { group: Cow<'static, str> },
    Package { name: String, version: String },
}

/// One part of a message. Structured parts let renderers style them and machine formats keep
/// them apart.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum MsgPart {
    Text(Cow<'static, str>),
    Code(String),
    Type(String),
    Num(i128),
}

/// A message, built from typed parts rather than formatted text.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Msg(pub Vec<MsgPart>);

impl Msg {
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    #[must_use]
    pub fn text(self, text: impl Into<Cow<'static, str>>) -> Self {
        self.part(MsgPart::Text(text.into()))
    }

    #[must_use]
    pub fn code(self, code: impl Into<String>) -> Self {
        self.part(MsgPart::Code(code.into()))
    }

    #[must_use]
    pub fn ty(self, ty: impl Into<String>) -> Self {
        self.part(MsgPart::Type(ty.into()))
    }

    #[must_use]
    pub fn num(self, n: impl Into<i128>) -> Self {
        self.part(MsgPart::Num(n.into()))
    }

    fn part(mut self, part: MsgPart) -> Self {
        self.0.push(part);
        self
    }
}

impl<T: Into<Cow<'static, str>>> From<T> for Msg {
    fn from(text: T) -> Self {
        Self(vec![MsgPart::Text(text.into())])
    }
}

/// Plain text, with code and types in backticks.
impl fmt::Display for Msg {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for part in &self.0 {
            match part {
                MsgPart::Text(t) => f.write_str(t)?,
                MsgPart::Code(c) | MsgPart::Type(c) => write!(f, "`{c}`")?,
                MsgPart::Num(n) => write!(f, "{n}")?,
            }
        }
        Ok(())
    }
}

/// A location, optionally annotated. Renderers follow the origin chain to show generated code
/// together with its generator.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Label {
    pub origin: OriginId,
    pub msg: Option<Msg>,
}

/// How safe it is to apply a fix without review.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Safety {
    /// Preserves meaning and compiles; the only kind applied automatically.
    Safe,
    /// May change behavior; applied only on request.
    Unsafe,
    /// Contains holes the user must fill.
    Placeholder,
    /// Shown, never applied.
    DisplayOnly,
}

/// A hole in a placeholder edit: a byte range of the edit text and the choices to offer.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Hole {
    pub range: (u32, u32),
    pub choices: Vec<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Edit {
    pub span: Span,
    pub text: String,
    pub holes: Vec<Hole>,
}

/// A proposed change; its edits never overlap.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Fix {
    pub msg: Msg,
    pub safety: Safety,
    pub edits: Vec<Edit>,
    pub preferred: bool,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ChildKind {
    /// A fact.
    Note,
    /// A suggestion.
    Help,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Child {
    pub kind: ChildKind,
    pub msg: Msg,
    pub labels: Vec<Label>,
    pub fixes: Vec<Fix>,
}

/// Context such as "while evaluating", "instantiated from", "generated by".
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TraceFrame {
    pub msg: Msg,
    pub origin: OriginId,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Diagnostic {
    pub id: DiagId,
    pub severity: Severity,
    pub source: DiagSource,
    pub message: Msg,
    /// `None` only when there is no source location, such as a missing input file.
    pub primary: Option<Label>,
    pub labels: Vec<Label>,
    pub children: Vec<Child>,
    pub fixes: Vec<Fix>,
    /// Innermost first.
    pub trace: Vec<TraceFrame>,
}

impl Diagnostic {
    #[must_use]
    pub fn new(id: DiagId, severity: Severity, message: impl Into<Msg>) -> Self {
        Self {
            id,
            severity,
            source: DiagSource::Compiler,
            message: message.into(),
            primary: None,
            labels: Vec::new(),
            children: Vec::new(),
            fixes: Vec::new(),
            trace: Vec::new(),
        }
    }

    #[must_use]
    pub fn error(id: DiagId, message: impl Into<Msg>) -> Self {
        Self::new(id, Severity::Error, message)
    }

    #[must_use]
    pub fn at(mut self, origin: OriginId, msg: Option<Msg>) -> Self {
        self.primary = Some(Label { origin, msg });
        self
    }

    #[must_use]
    pub fn child(mut self, kind: ChildKind, msg: impl Into<Msg>) -> Self {
        self.children.push(Child { kind, msg: msg.into(), labels: Vec::new(), fixes: Vec::new() });
        self
    }
}

/// Proof that an error was emitted. Only [`DiagCtxt`] creates one, so a poisoned type or value
/// carrying it guarantees that the build fails and that later diagnostics about it can be dropped.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct ErrorGuaranteed(());

/// Output for diagnostics: terminal, short, JSON, SARIF, LSP.
pub trait DiagSink {
    fn emit(&mut self, d: &Diagnostic, origins: &OriginTable, sources: &dyn SourceMap);
}

/// Collects diagnostics for one compilation.
#[derive(Default)]
pub struct DiagCtxt {
    diagnostics: Vec<Diagnostic>,
}

impl DiagCtxt {
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Records an error and returns the proof that it was emitted.
    pub fn error(&mut self, mut d: Diagnostic) -> ErrorGuaranteed {
        d.severity = Severity::Error;
        self.diagnostics.push(d);
        ErrorGuaranteed(())
    }

    pub fn report(&mut self, d: Diagnostic) {
        self.diagnostics.push(d);
    }

    #[must_use]
    pub fn error_count(&self) -> usize {
        self.diagnostics.iter().filter(|d| d.severity == Severity::Error).count()
    }

    /// All diagnostics in a deterministic order (by primary origin, then id), independent of the
    /// order in which parallel work reported them.
    #[must_use]
    pub fn sorted(&self) -> Vec<&Diagnostic> {
        let mut all: Vec<&Diagnostic> = self.diagnostics.iter().collect();
        all.sort_by(|a, b| {
            let origin = |d: &Diagnostic| d.primary.as_ref().map(|l| l.origin);
            origin(a).cmp(&origin(b)).then_with(|| a.id.cmp(&b.id))
        });
        all
    }
}
