use crate::{Reference, Uri};

/// RFC 3986, section 5.4: each reference, and the URI it resolves to from `BASE`.
const BASE: &str = "http://a/b/c/d;p?q";

const NORMAL: &[(&str, &str)] = &[
    ("g:h", "g:h"),
    ("g", "http://a/b/c/g"),
    ("./g", "http://a/b/c/g"),
    ("g/", "http://a/b/c/g/"),
    ("/g", "http://a/g"),
    ("//g", "http://g"),
    ("?y", "http://a/b/c/d;p?y"),
    ("g?y", "http://a/b/c/g?y"),
    ("#s", "http://a/b/c/d;p?q#s"),
    ("g#s", "http://a/b/c/g#s"),
    ("g?y#s", "http://a/b/c/g?y#s"),
    (";x", "http://a/b/c/;x"),
    ("g;x", "http://a/b/c/g;x"),
    ("g;x?y#s", "http://a/b/c/g;x?y#s"),
    ("", "http://a/b/c/d;p?q"),
    (".", "http://a/b/c/"),
    ("./", "http://a/b/c/"),
    ("..", "http://a/b/"),
    ("../", "http://a/b/"),
    ("../g", "http://a/b/g"),
    ("../..", "http://a/"),
    ("../../", "http://a/"),
    ("../../g", "http://a/g"),
];

const ABNORMAL: &[(&str, &str)] = &[
    ("../../../g", "http://a/g"),
    ("../../../../g", "http://a/g"),
    ("/./g", "http://a/g"),
    ("/../g", "http://a/g"),
    ("g.", "http://a/b/c/g."),
    (".g", "http://a/b/c/.g"),
    ("g..", "http://a/b/c/g.."),
    ("..g", "http://a/b/c/..g"),
    ("./../g", "http://a/b/g"),
    ("./g/.", "http://a/b/c/g/"),
    ("g/./h", "http://a/b/c/g/h"),
    ("g/../h", "http://a/b/c/h"),
    ("g;x=1/./y", "http://a/b/c/g;x=1/y"),
    ("g;x=1/../y", "http://a/b/c/y"),
    ("g?y/./x", "http://a/b/c/g?y/./x"),
    ("g?y/../x", "http://a/b/c/g?y/../x"),
    ("g#s/./x", "http://a/b/c/g#s/./x"),
    ("g#s/../x", "http://a/b/c/g#s/../x"),
    // The strict parser: a scheme names itself even when it is the base's.
    ("http:g", "http:g"),
];

#[test]
fn every_example_of_rfc_3986_resolves_as_written() {
    let base: Uri = BASE.parse().unwrap();
    for &(reference, expected) in NORMAL.iter().chain(ABNORMAL) {
        let reference: Reference = reference.parse().unwrap();
        let resolved = base.resolve(&reference);
        assert_eq!(resolved.as_str(), expected, "{reference}");
        resolved.verify().unwrap();
    }
}

#[test]
fn a_path_resolved_to_start_with_two_slashes_keeps_reading_as_a_path() {
    let base: Uri = "a:/b/c".parse().unwrap();
    let resolved = base.join("..//x").unwrap();
    assert_eq!(resolved.as_str(), "a:/.//x");
    resolved.verify().unwrap();
    assert_eq!(resolved.authority(), None);
}
